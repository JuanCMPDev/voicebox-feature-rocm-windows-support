"""
Serial generation queue — ensures only one TTS inference runs at a time
to avoid GPU contention. Transcriptions take turns with it through the
same GPU lock. Queued jobs that share a batch key run as one batch
(opt-in, see ``services.generation.batch_key``).
"""

import asyncio
import contextvars
import traceback
from collections.abc import Awaitable, Callable, Coroutine, Hashable
from dataclasses import dataclass
from typing import Any, Literal

# Most jobs one batch takes from the queue (the job that got the GPU plus up to three queued behind it).
MAX_BATCH_SIZE = 4

# Keep references to fire-and-forget background tasks to prevent GC
_background_tasks: set = set()


@dataclass
class GenerationJob:
    """Queued generation work plus the generation ID it belongs to.

    Jobs with the same non-None ``batch_key`` may run together as one batch.
    """

    generation_id: str
    coro: Coroutine
    batch_key: Hashable | None = None


class GenerationBatch:
    """Requests of the jobs the worker runs together, generated by one call.

    The worker starts the jobs one at a time and lets each run until it hands its request to :meth:`generate` (or
    ends), so model loads, voice prompts and status updates happen in queue order, as they do for single jobs. Then
    :meth:`run` generates every request in one call and each job carries on with its own result.
    """

    def __init__(self) -> None:
        self._requests: list[tuple[Any, asyncio.Future]] = []
        self._run_requests: Callable[[list[Any]], Awaitable[list[Any]]] | None = None
        self._arrival: asyncio.Future | None = None

    async def generate(self, request: Any, run_requests: Callable[[list[Any]], Awaitable[list[Any]]]) -> Any:
        """Hand over this job's request and wait for its result.

        Args:
            request: What the job needs generated; only ``run_requests`` looks inside.
            run_requests: Generates a list of requests in one go and returns, aligned with them, each one's result or
                the exception it failed with. The first job's function serves the whole batch.

        Returns:
            This request's result; its exception is raised instead.
        """
        future = asyncio.get_running_loop().create_future()
        self._requests.append((request, future))
        if self._run_requests is None:
            self._run_requests = run_requests
        if self._arrival is not None and not self._arrival.done():
            self._arrival.set_result(None)
        return await future

    async def admit(self, task: asyncio.Task) -> None:
        """Wait until ``task``, a job just started, hands over its request or ends."""
        self._arrival = asyncio.get_running_loop().create_future()
        try:
            await asyncio.wait({task, self._arrival}, return_when=asyncio.FIRST_COMPLETED)
        finally:
            self._arrival.cancel()
            self._arrival = None

    async def run(self) -> None:
        """Generate the requests still awaited in one call and hand each job its result or error.

        Requests of jobs cancelled while they waited are left out.
        """
        pending = [(request, future) for request, future in self._requests if not future.done()]
        if not pending or self._run_requests is None:
            return
        try:
            outcomes = list(await self._run_requests([request for request, _ in pending]))
            if len(outcomes) != len(pending):
                raise RuntimeError(f"batch returned {len(outcomes)} results for {len(pending)} requests")
        except Exception as error:
            outcomes = [error] * len(pending)
        for (_, future), outcome in zip(pending, outcomes, strict=True):
            if future.done():
                continue
            if isinstance(outcome, BaseException):
                future.set_exception(outcome)
            else:
                future.set_result(outcome)


# Batch of the running job; the worker sets it only around the creation of a batched job's task, which copies it.
_current_batch: contextvars.ContextVar[GenerationBatch | None] = contextvars.ContextVar(
    "generation_batch", default=None
)


def current_batch() -> GenerationBatch | None:
    """Batch the running generation job belongs to, or None when it runs on its own."""
    return _current_batch.get()


# Generation queue — serializes TTS inference to avoid GPU contention
_generation_queue: asyncio.Queue = None  # type: ignore  # initialized at startup
_generation_worker_task: asyncio.Task | None = None
_queued_generation_ids: set[str] = set()
_running_generation_tasks: dict[str, asyncio.Task] = {}
_cancelled_generation_ids: set[str] = set()

# GPU turn shared by queued generations and /transcribe (/generate/stream bypasses the queue and does not take it).
# asyncio.Lock wakes waiters in arrival order and acquire() never overtakes a waiter, so a transcription that arrives
# during a generation runs right after it, ahead of the generations still queued: it waits for one generation (or one
# batch) at most.
_gpu_lock: asyncio.Lock | None = None


def gpu_lock() -> asyncio.Lock:
    """Lock held by each queued generation and each transcription while it runs."""
    global _gpu_lock
    if _gpu_lock is None:
        _gpu_lock = asyncio.Lock()
    return _gpu_lock


def create_background_task(coro) -> asyncio.Task:
    """Create a background task and prevent it from being garbage collected."""
    task = asyncio.create_task(coro)
    _background_tasks.add(task)
    task.add_done_callback(_background_tasks.discard)
    return task


async def _generation_worker():
    """Worker that processes generation tasks one at a time, or one batch of compatible queued jobs at a time."""
    while True:
        job = await _generation_queue.get()
        jobs = [job]
        try:
            # The job stays queued, and cancellable as such, until it gets the GPU.
            async with gpu_lock():
                if job.generation_id in _cancelled_generation_ids:
                    _cancelled_generation_ids.discard(job.generation_id)
                    job.coro.close()
                    continue

                jobs += _take_batch_partners(job)
                if len(jobs) > 1:
                    await _run_batch(jobs)
                    continue

                task = asyncio.create_task(job.coro)
                _running_generation_tasks[job.generation_id] = task
                _queued_generation_ids.discard(job.generation_id)
                try:
                    await task
                except asyncio.CancelledError:
                    if not task.cancelled():
                        raise
        except Exception:
            traceback.print_exc()
            for failed in jobs:
                await _force_fail_if_active(
                    failed.generation_id,
                    "Worker exited without writing terminal status",
                )
        finally:
            for finished in jobs:
                _running_generation_tasks.pop(finished.generation_id, None)
                _queued_generation_ids.discard(finished.generation_id)
                _generation_queue.task_done()


def _take_batch_partners(job: GenerationJob) -> list[GenerationJob]:
    """Take out of the queue the jobs that run in one batch with ``job``: same non-None key, not cancelled.

    At most ``MAX_BATCH_SIZE - 1`` of them. The queue is emptied and the other jobs go back in their order; there is
    no await in between, so nothing can be enqueued meanwhile.
    """
    if job.batch_key is None:
        return []
    partners: list[GenerationJob] = []
    others: list[GenerationJob] = []
    while True:
        try:
            queued = _generation_queue.get_nowait()
        except asyncio.QueueEmpty:
            break
        if (
            len(partners) < MAX_BATCH_SIZE - 1
            and queued.batch_key == job.batch_key
            and queued.generation_id not in _cancelled_generation_ids
        ):
            partners.append(queued)
        else:
            others.append(queued)
    for queued in others:
        _generation_queue.put_nowait(queued)
        _generation_queue.task_done()  # put_nowait counted it again; the worker's task_done is for the second get
    return partners


async def _run_batch(jobs: list[GenerationJob]) -> None:
    """Run ``jobs`` as one batch: each prepares in turn up to its generation, then one call generates for all."""
    batch = GenerationBatch()
    started: dict[str, asyncio.Task] = {}
    try:
        for job in jobs:
            # Still queued (and cancellable as such) while the jobs before it prepare.
            if job.generation_id in _cancelled_generation_ids:
                _cancelled_generation_ids.discard(job.generation_id)
                continue
            token = _current_batch.set(batch)
            try:
                task = asyncio.create_task(job.coro)
            finally:
                _current_batch.reset(token)
            started[job.generation_id] = task
            _running_generation_tasks[job.generation_id] = task
            _queued_generation_ids.discard(job.generation_id)
            await batch.admit(task)

        await batch.run()

        for generation_id, task in started.items():
            try:
                await task
            except asyncio.CancelledError:
                if not task.cancelled():
                    raise
            except Exception:
                traceback.print_exc()
                await _force_fail_if_active(generation_id, "Worker exited without writing terminal status")
    finally:
        for job in jobs:
            if job.generation_id not in started:
                job.coro.close()


async def _force_fail_if_active(generation_id: str, error: str) -> None:
    """Best-effort recovery — flip an active row to failed if the worker
    bailed before writing a terminal status. Catches the case where the gen
    coroutine's own status-write raised (e.g. SQLite lock contention)."""
    try:
        from ..database import Generation as DBGeneration, get_db
        from . import history

        db = next(get_db())
        try:
            gen = db.query(DBGeneration).filter_by(id=generation_id).first()
            if gen is None:
                return
            if (gen.status or "completed") not in ("queued", "loading_model", "generating"):
                return
            await history.update_generation_status(
                generation_id=generation_id,
                status="failed",
                db=db,
                error=error,
            )
        finally:
            db.close()
    except Exception:
        traceback.print_exc()


def enqueue_generation(generation_id: str, coro, batch_key: Hashable | None = None):
    """Add a generation coroutine to the serial queue.

    Args:
        generation_id: Generation the coroutine works for.
        coro: The work, normally ``services.generation.run_generation(...)``.
        batch_key: From ``services.generation.batch_key``; None (the default) never batches.
    """
    if _generation_queue is None:
        raise RuntimeError("Generation queue has not been initialized")

    _queued_generation_ids.add(generation_id)
    _generation_queue.put_nowait(GenerationJob(generation_id=generation_id, coro=coro, batch_key=batch_key))


def cancel_generation(generation_id: str) -> Literal["queued", "running"] | None:
    """Cancel a queued or running generation if it is still active."""
    running_task = _running_generation_tasks.get(generation_id)
    if running_task is not None:
        running_task.cancel()
        return "running"

    if generation_id in _queued_generation_ids:
        _queued_generation_ids.discard(generation_id)
        _cancelled_generation_ids.add(generation_id)
        return "queued"

    return None


def init_queue(force: bool = False):
    """Initialize the generation queue and start the worker.

    Must be called once during application startup (inside a running event loop).
    """
    global _generation_queue, _generation_worker_task, _gpu_lock
    global _queued_generation_ids, _running_generation_tasks, _cancelled_generation_ids

    if _generation_worker_task is not None and not _generation_worker_task.done():
        if not force:
            return
        _generation_worker_task.cancel()
        for task in list(_running_generation_tasks.values()):
            task.cancel()

    _generation_queue = asyncio.Queue()
    _gpu_lock = asyncio.Lock()
    _queued_generation_ids = set()
    _running_generation_tasks = {}
    _cancelled_generation_ids = set()
    _generation_worker_task = create_background_task(_generation_worker())
